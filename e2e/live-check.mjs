import { chromium } from 'playwright-core'
const BASE = 'https://2hand.vhphuoc.io.vn'
const b = await chromium.launch({ executablePath: process.env.CHROME, args: ['--no-sandbox'] })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, locale: 'vi-VN' })
const p = await ctx.newPage()
p.on('dialog', (d) => d.accept())
const errs = []
p.on('pageerror', (e) => errs.push(String(e)))
p.on('console', (m) => m.type() === 'error' && errs.push(m.text().slice(0, 200)))
const step = (s) => console.log('STEP', s)
const fail = async (s) => { console.log('FAIL', s, '\n', (await p.textContent('main').catch(() => '')).replace(/\s+/g, ' ').slice(0, 500)); await p.screenshot({ path: 'e2e/screens/live-fail.png', fullPage: true }); console.log('errors', errs); await b.close(); process.exit(1) }
await p.goto(BASE + '/', { waitUntil: 'load' })
await p.waitForSelector('[data-testid=result-count]', { timeout: 20000 }).catch(() => {})
const body = await p.textContent('body')
if (body.includes('đang được cấu hình')) await fail('banner vẫn còn')
if (body.includes('Không tải được')) await fail('trang chủ báo lỗi tải tin')
step('Không còn banner "Hệ thống đang được cấu hình", trang chủ không báo lỗi tải tin')
await p.screenshot({ path: 'e2e/screens/live-01-trang-chu.png' })
const email = `selftest.${Date.now()}@vhphuoc.io.vn`
await p.goto(BASE + '/dang-ky')
await p.fill('#r-name', 'Devin Test')
await p.fill('#r-email', email)
await p.fill('#r-pass', 'Selftest#2026')
await p.fill('#r-phone', '0988474228')
await p.selectOption('#r-province', 'TP. Hồ Chí Minh')
await p.click('[data-testid=register-submit]')
await p.waitForURL(BASE + '/', { timeout: 20000 }).catch(() => fail('đăng ký'))
step('Đăng ký ' + email)
// logout + login to prove login works
await p.goto(BASE + '/tai-khoan')
await p.waitForSelector('#p-phone', { timeout: 15000 }).catch(() => fail('hồ sơ'))
if ((await p.inputValue('#p-phone')) !== '0988474228') await fail('hồ sơ chưa lưu vào Firestore')
step('Hồ sơ người bán lưu Firestore OK')
console.log('EMAIL', email)
await p.goto(BASE + '/dang-tin')
await p.fill('#title', 'TIN TEST — Devin kiểm tra hệ thống (sẽ xoá)')
await p.locator('[data-testid=category-checklist] label').first().click()
await p.locator('[data-testid=condition-options] label', { hasText: 'Như mới' }).click()
await p.fill('#price', '123000')
await p.fill('#desc', 'Tin kiểm tra tự động sau khi gắn Firebase. Sẽ xoá ngay.')
await p.setInputFiles('[data-testid=image-file]', '/tmp/2hand-a.png')
await p.waitForSelector('img[alt="Ảnh 1"]')
await p.click('[data-testid=submit-listing]')
await p.waitForURL(/tin-cua-toi\?tab=pending/, { timeout: 20000 }).catch(() => fail('đăng tin'))
await p.waitForSelector('[data-testid=my-listing]', { timeout: 15000 }).catch(() => fail('tin không hiện trong Tin của tôi'))
step('Đăng tin → "Chờ duyệt" trong Tin của tôi')
await p.screenshot({ path: 'e2e/screens/live-02-tin-cho-duyet.png' })
// sign out, sign in again
await p.evaluate(() => localStorage.clear())
await ctx.clearCookies()
const p2 = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true })).newPage()
p2.on('dialog', (d) => d.accept())
await p2.goto(BASE + '/dang-nhap')
await p2.fill('#l-email', email)
await p2.fill('#l-pass', 'Selftest#2026')
await p2.click('[data-testid=login-submit]')
await p2.waitForURL((u) => u.pathname === '/', { timeout: 20000 }).catch(() => fail('đăng nhập lại'))
await p2.goto(BASE + '/tin-cua-toi?tab=pending')
await p2.waitForSelector('[data-testid=my-listing]', { timeout: 15000 }).catch(() => fail('sau đăng nhập không thấy tin'))
step('Đăng nhập lại bằng email/mật khẩu OK, thấy tin chờ duyệt')
await p2.locator('[data-testid=delete-listing]').first().click()
await p2.waitForFunction(() => !document.querySelector('[data-testid=my-listing]'), null, { timeout: 15000 }).catch(() => fail('xoá tin test'))
step('Xoá tin test OK')
// guest: pending listing not public, market loads without errors
const g = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage()
await g.goto(BASE + '/', { waitUntil: 'load' })
await g.waitForSelector('[data-testid=result-count]', { timeout: 15000 }).catch(() => fail('chợ không tải'))
await g.waitForTimeout(3000)
if ((await g.textContent('body')).includes('Không tải được')) await fail('trang chủ báo "Không tải được danh sách tin"')
step('Trang chủ (khách) tải danh sách OK, không báo lỗi: ' + (await g.textContent('[data-testid=result-count]')))
await g.screenshot({ path: 'e2e/screens/live-03-trang-chu-khach.png' })
console.log('errors', errs)
await b.close()
